/**
 * 동적 라우트 세그먼트를 **API에 넘길 수 있는 값**으로 되돌린다.
 *
 * ⚠️ Next 16.3에서 `params`가 **호출부에 따라 다른 모양으로 온다**
 *    (2026-09-02 실측, 같은 요청 하나에서):
 *
 *      generateMetadata → 디코드됨    "주일-예배-시간-안내"
 *      페이지 컴포넌트   → 인코드됨    "%EC%A3%BC%EC%9D%BC-%EC%98%88%EB%B0%B0-..."
 *
 *    한글 slug 라우트에서 후자를 그대로 API 계층에 넘기면
 *    `encodeURIComponent`가 한 번 더 걸려 **이중 인코딩**된 경로가 나간다:
 *
 *      GET /api/posts/%25EC%25A3%25BC%25EC%259D%25BC-...
 *
 *    서버는 그 퍼센트 문자열 자체를 slug로 찾다 실패한다. 화면에는
 *    "찾을 수 없는 글"(404를 주는 서버) 또는 로그인 안내(401을 주는 서버)가
 *    뜨는데, **URL도 정상이고 서버도 정상**이라 원인이 보이지 않는다.
 *
 * 그래서 세그먼트를 API에 넘기는 곳은 전부 이 함수를 통과시킨다. 이미
 * 디코드된 값에는 아무 일도 일어나지 않으므로(`%`가 없다) 양쪽 호출부가
 * 같은 문자열을 만들고, `cache()`의 중복 제거도 다시 동작한다 — 지금은
 * 두 호출부가 서로 다른 키를 만들어 같은 글을 두 번 조회하고 있다.
 *
 * ⚠️ ASCII id(`[id]` 라우트)는 인코딩과 무관해 영향이 없다. 이 함수가 필요한
 *    곳은 **한글 slug를 쓰는 라우트**다 (`/news/[slug]` · `/documents/[slug]`).
 */
export function decodeRouteParam(value: string): string {
  try {
    return decodeURIComponent(value);
  } catch {
    /*
      잘못된 퍼센트 시퀀스(`%zz` 등)면 던진다. 여기서 터뜨리지 않고 원본을
      그대로 넘겨 서버 판정(404)에 맡긴다 — 주소창에 이상한 값을 넣은 것이
      500이 될 이유가 없다.
    */
    return value;
  }
}
