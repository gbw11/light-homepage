package kr.light.common;

/**
 * 감사 로그에 남기는 행위.
 *
 * <p>DB에는 문자열로 저장된다(varchar(50)). 오타로 조회가 어긋나는 것을 막기
 * 위해 열거형으로 좁혀둔다. 필요한 행위가 생기면 여기에 추가한다.
 */
public enum AuditAction {
    /** 회원 승인 — PENDING → MEMBER */
    /** 회원 가입 거절 */
    /**
     * 계정 삭제 + 명단 재개방 (SPEC_API.md §8.2).
     *
     * <p>선점 복구 절차의 기록이다 — 회원 행이 사라지므로 <b>사유가 담긴
     * 이 로그가 유일한 기록</b>이다.
     */
    MEMBER_DELETE,
    /** 역할 부여·변경 */
    ROLE_CHANGE,

    /**
     * 비밀번호 리셋 코드 발급 (SPEC_API.md §8.4).
     *
     * <p>남의 비밀번호를 바꿀 수 있는 값을 사람에게 건네는 동작이다.
     * 본인 확인의 근거가 시스템이 아니라 전도사의 판단이므로,
     * <b>누가 누구에게 언제 발급했는지</b>가 유일한 기록이 된다.
     */
    PASSWORD_RESET_ISSUE,

    /**
     * 본인 탈퇴 (SPEC_API.md §2.12).
     *
     * <p>회원 행이 사라지므로 actor는 {@code ON DELETE SET NULL}로 null이
     * 된다. 그래도 대상과 시각은 남아 "언제 누가 나갔는지"를 알 수 있다.
     */
    MEMBER_WITHDRAW,

    /**
     * 사진 신고·삭제 요청 (SPEC_API.md §6.10).
     *
     * <p>다른 값들과 달리 <b>무언가를 바꾼 기록이 아니라 요청의 기록</b>이다.
     * 그래도 여기에 남기는 이유는 같다 — 초상권 요청은 <b>이 기록이
     * 사라지면 요청 자체가 사라지기 때문</b>이다. 계약(§6.10)에 임원이
     * 신고를 조회하는 경로가 없어, 지금은 이 로그가 유일한 보관처다.
     */
    PHOTO_REPORT
}
