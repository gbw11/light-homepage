package kr.light.sermon;

import java.util.regex.Pattern;

/**
 * 채널 영상 중 <b>무엇이 설교인가</b>를 가린다.
 *
 * <h2>왜 필요한가</h2>
 * 채널에는 설교만 있지 않다 — 수련회 보고영상·브이로그·찬양 커버·다큐
 * 시리즈가 섞여 있다. 그것들이 "말씀" 목록에 뜨면 화면의 뜻이 흐려진다.
 *
 * <h2>★ 제목 형식이 시대별로 세 가지다</h2>
 * 실제 채널 210편을 전부 훑어 확인했다 (2026-09-02).
 * <pre>
 *   ① 2026~      2026년 8월 30일 l 하나님께 소망을 두고 있나요? l [김해교회…]
 *   ② 2025 후반   세상을 밝히는 빛, LIGHT 공동체/2025-10-12/주일 예배/"모두에게…"
 *   ③ 2024~2025   세상을 밝히는 빛, LIGHT 공동체 2025-2-23 청년교회 주일 예배/"…"
 * </pre>
 *
 * <p>⚠️ 처음에는 <b>①만</b> 잡는 규칙("제목이 날짜로 시작")을 썼다 —
 * FE의 임시 RSS 라우트가 쓰던 규칙을 그대로 옮긴 것이었다. 그런데 RSS는
 * 최신 15편만 주므로 ②③이 애초에 보이지 않았고, <b>210편 중 38편만</b>
 * 설교로 잡혔다. 지난 말씀 화면이 설교 4분의 1만 보여줄 상태였다.
 *
 * <p>그래서 <b>"연-월-일이 어디든 있으면 설교"</b>로 바꿨다. 세 형식 모두
 * 날짜를 담고 있고, 이 규칙이 <b>154편</b>을 잡는다. "주일 예배" 문구가
 * 들어간 영상은 <b>하나도 놓치지 않는다</b>(측정 확인).
 *
 * <h2>⚠️ 이 규칙은 여전히 임시다</h2>
 * 제목 규칙은 <b>채널이 작명을 바꾸면 조용히 무너진다</b> — 실제로 이미 세
 * 번 바뀌었다. 설교만 담은 <b>재생목록</b>이 만들어지면 그쪽이 정답이다
 * (SPEC_API §9.2의 ❓ "PM 확인 필요"). {@code app.youtube.playlist-id}를
 * 채우면 이 필터는 쓰이지 않는다.
 *
 * <p>남는 불확실성: 날짜가 없는 제목({@code "신앙의 클리셰를 깨라"} 등)은
 * 설교인지 시리즈 예고인지 제목만으로 가릴 수 없어 제외된다.
 */
public final class SermonTitles {

    /**
     * 제목에 <b>연-월-일</b>이 있는가.
     *
     * <ul>
     *   <li>{@code 2026년 8월 30일} — 형식 ①</li>
     *   <li>{@code 2025-10-12} · {@code 2025-2-23} — 형식 ②③ (한 자리 월·일 있음)</li>
     *   <li>{@code 2025.10.12} — 점 구분도 함께 받는다</li>
     * </ul>
     *
     * <p>⚠️ <b>연도만 있는 제목은 걸러야 한다.</b> {@code "2026 하계수련회 보고영상"}
     * {@code "김해교회 LIGHT 청년교회 | 오프닝 | 2026"}이 설교로 잡히면 안 되므로
     * <b>월·일까지 모두</b> 요구한다.
     */
    private static final Pattern SERMON_DATE = Pattern.compile(
            "\\d{4}\\s*[-.]\\s*\\d{1,2}\\s*[-.]\\s*\\d{1,2}"      // 2025-2-23 · 2025.10.12
                    + "|\\d{4}년\\s*\\d{1,2}월\\s*\\d{1,2}일");   // 2026년 8월 30일

    private SermonTitles() {
    }

    public static boolean isSermon(String title) {
        return title != null && SERMON_DATE.matcher(title).find();
    }
}
