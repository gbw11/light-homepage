--  V5 — slug는 모든 분류가 갖는다 (SPEC_API.md §3.2 · §3.3)
--
--  ⚠️ V1의 `slug varchar(200), -- 공개 공지만 사용` 주석은 사실이 아니었다.
--     계약서는 slug를 항상 문자열로 정의하는데 우리만 비공개 분류에서
--     null을 내보내고 있었고, FE는 문서대로 slug: string으로 받아
--     /news/{slug} 링크를 만들었다 — 회원 전용 공지를 누르면 /news/null로
--     갔다 (2026-09-02 FE 통합 확인에서 발견).
--
--     V1은 이미 머지돼 체크섬이 고정돼 있어 고칠 수 없다. 여기서 바로잡는다.
-- ═══════════════════════════════════════════════════════════════════════


-- ───────────────────────────────────────────────────────────────────────
--  §1. 기존 행 채우기
--
--  제목에서 만드는 규칙은 Java에 있다(PostSlugGenerator — NFC 정규화, 한글
--  보존, 충돌 시 -2 접미사). SQL로 그것을 흉내 내면 <같은 제목인데 다른
--  slug>가 생겨 더 혼란스럽다.
--
--  그래서 id 기반의 확실히 유일한 값으로 채운다. 예쁘지 않지만 깨지지 않고,
--  ★ 그 글을 한 번 수정하면 PostSlugGenerator가 제목 기반으로 다시 만든다.
--  (지금 이 값을 갖는 것은 v1.3 이전에 만들어진 비공개 글뿐이다)
-- ───────────────────────────────────────────────────────────────────────
UPDATE posts SET slug = 'post-' || id WHERE slug IS NULL;


-- ───────────────────────────────────────────────────────────────────────
--  §2. 계약을 DB가 지키게 한다
--
--  "slug는 항상 있다"가 계약이므로 null을 넣을 수 없게 막는다. 앞으로
--  slug 없이 글을 만드는 경로가 생기면 <조용히 null이 나가는 대신>
--  여기서 터진다 — FE가 /news/null로 가는 것보다 훨씬 낫다.
-- ───────────────────────────────────────────────────────────────────────
ALTER TABLE posts ALTER COLUMN slug SET NOT NULL;

COMMENT ON COLUMN posts.slug IS
    '제목에서 만든 주소용 식별자. 모든 분류가 갖는다 (SPEC_API §3.2). '
    '비공개 글에도 있지만 열람은 분류별 권한이 막는다 — slug를 안다고 볼 수 있는 것이 아니다';
