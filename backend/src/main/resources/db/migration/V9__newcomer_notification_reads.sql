-- ═══════════════════════════════════════════════════════════════════════
--  V9 — 새가족 신청 알림 읽음 표시
--
--  새가족 신청이 들어오면 전도사·임원에게 알린다. 원래 계약(§9.1)은
--  "알림 메일"이었는데, 메일 계정·발신 도메인 결정이 필요해 막혀 있었다.
--  → 웹 알림(관리 화면 배지)으로 바꿨다 (2026-09-09 결정).
-- ═══════════════════════════════════════════════════════════════════════


-- ───────────────────────────────────────────────────────────────────────
--  ★ 알림 행을 따로 만들지 않는다
--
--  "안 읽은 새가족 신청"은 newcomer_requests에 이미 다 있다. 알림 테이블을
--  만들어 같은 내용을 복사하면 두 곳이 어긋날 수 있고(신청은 지웠는데 알림은
--  남는 식), 보유기간 1년 삭제(§8.6)도 두 곳을 봐야 한다.
--
--  그래서 저장하는 것은 **사람마다 "어디까지 봤는지" 시각 하나**뿐이다.
--  안 읽은 목록 = 그 시각 이후에 들어온 신청.
--
--  ⚠️ 알림 종류가 늘어나면(사진 신고·용량 경고 등) 이 방식으로는 부족하다.
--     그때는 type을 가진 알림 테이블이 필요하다 — 지금은 새가족 하나뿐이라
--     (2026-09-09 결정) 가장 단순한 형태로 둔다.
--
--  ★ 읽음은 **사람별**이다. 팀 공유로 두면 한 사람이 열어본 것만으로 알림이
--    사라지는데, 그 사람이 실제로 연락했다는 뜻은 아니다. 새가족 연락은
--    늦어도 되지만 빠뜨리면 안 되는 종류라 각자에게 남게 한다.
-- ───────────────────────────────────────────────────────────────────────
CREATE TABLE newcomer_notification_reads (
    -- 사람마다 한 줄. 계정이 지워지면 표시도 함께 사라진다
    member_id    bigint      PRIMARY KEY,

    -- 이 시각까지의 신청을 봤다. 이후에 들어온 것이 "안 읽음"이다
    last_seen_at timestamptz NOT NULL,

    updated_at   timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT newcomer_notification_reads_member_fk FOREIGN KEY (member_id)
        REFERENCES members (id) ON DELETE CASCADE
);

COMMENT ON TABLE newcomer_notification_reads IS
    '새가족 신청 알림을 사람별로 어디까지 봤는지. 알림 내용은 newcomer_requests가 갖는다';
COMMENT ON COLUMN newcomer_notification_reads.last_seen_at IS
    '이 시각 이후에 들어온 신청이 안 읽음이다. 행이 없으면 전부 안 읽음';
