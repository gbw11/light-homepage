-- ═══════════════════════════════════════════════════════════════════════
--  V10 — 새가족 신청: 나이대 대신 생년월일 (2026-10-19 결정, §9.1 [CONTRACT])
--
--  나이대(20대 초반 등 4칸)로는 새가족마을 편성에 쓸 수 없어 생년월일을 받는다.
--  API에서는 필수다.
-- ═══════════════════════════════════════════════════════════════════════

-- 기존 신청에는 생년월일이 없다 — 그래서 컬럼은 NULL을 허용한다.
-- 필수 여부는 API(§9.1)가 지킨다
ALTER TABLE newcomer_requests ADD COLUMN birth_date date;

ALTER TABLE newcomer_requests ADD CONSTRAINT newcomer_birth_date_ck
    CHECK (birth_date IS NULL OR birth_date >= DATE '1900-01-01');

-- ───────────────────────────────────────────────────────────────────────
--  ★ age_group은 지우지 않는다
--
--  지우면 이미 받은 신청의 나이대가 되돌릴 수 없게 사라진다. 운영 DB에서
--  되돌릴 수 없는 일을 이 변경에 끼워 넣지 않는다. 더 이상 쓰지 않는 컬럼으로
--  남겨두고, 보유기간(1년, §8.6)이 지나 기존 행이 모두 지워지면 그때 DROP한다.
-- ───────────────────────────────────────────────────────────────────────
COMMENT ON COLUMN newcomer_requests.age_group IS
    '더 이상 쓰지 않는다 (V10, 2026-10-19 생년월일로 교체). 기존 행 보존용 — 보유기간이 지나면 DROP';
COMMENT ON COLUMN newcomer_requests.birth_date IS
    '생년월일. API에서 필수(§9.1). V10 이전 신청은 NULL';
